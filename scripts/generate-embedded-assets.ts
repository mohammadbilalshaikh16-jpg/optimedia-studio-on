import fs from 'fs';
import path from 'path';

function getMimeType(filePath: string): string {
  const ext = path.extname(filePath).toLowerCase();
  switch (ext) {
    case '.html': return 'text/html; charset=utf-8';
    case '.js': return 'application/javascript; charset=utf-8';
    case '.css': return 'text/css; charset=utf-8';
    case '.json': return 'application/json; charset=utf-8';
    case '.svg': return 'image/svg+xml';
    case '.png': return 'image/png';
    case '.jpg':
    case '.jpeg': return 'image/jpeg';
    case '.webp': return 'image/webp';
    case '.ico': return 'image/x-icon';
    case '.woff2': return 'font/woff2';
    case '.woff': return 'font/woff';
    case '.ttf': return 'font/ttf';
    default: return 'application/octet-stream';
  }
}

function walkDir(dir: string, baseDir: string = dir): string[] {
  let results: string[] = [];
  const list = fs.readdirSync(dir);
  for (const file of list) {
    const fullPath = path.join(dir, file);
    const stat = fs.statSync(fullPath);
    if (stat && stat.isDirectory()) {
      results = results.concat(walkDir(fullPath, baseDir));
    } else {
      results.push(fullPath);
    }
  }
  return results;
}

export function generateEmbeddedAssets() {
  const distDir = path.resolve(process.cwd(), 'dist');
  if (!fs.existsSync(distDir)) {
    throw new Error('dist directory does not exist! Run "npm run build" first.');
  }

  const files = walkDir(distDir);
  const assets: Record<string, { contentType: string; data: string; isBase64: boolean }> = {};

  for (const filePath of files) {
    const relPath = '/' + path.relative(distDir, filePath).replace(/\\/g, '/');
    const mime = getMimeType(filePath);
    const isText = mime.startsWith('text/') || mime.includes('javascript') || mime.includes('json') || mime.includes('svg');

    if (isText) {
      const content = fs.readFileSync(filePath, 'utf-8');
      assets[relPath] = {
        contentType: mime,
        data: content,
        isBase64: false,
      };
    } else {
      const content = fs.readFileSync(filePath).toString('base64');
      assets[relPath] = {
        contentType: mime,
        data: content,
        isBase64: true,
      };
    }
  }

  const generatedCode = `/**
 * AUTO-GENERATED FILE - DO NOT EDIT MANUALLY.
 * Generated by scripts/generate-embedded-assets.ts
 * Embeds all frontend static assets inside the standalone executable.
 */

export interface EmbeddedAsset {
  contentType: string;
  data: string;
  isBase64: boolean;
}

export const EMBEDDED_ASSETS: Record<string, EmbeddedAsset> = ${JSON.stringify(assets, null, 2)};
`;

  const outputPath = path.resolve(process.cwd(), 'src', 'embedded-assets.generated.ts');
  fs.writeFileSync(outputPath, generatedCode, 'utf-8');
  console.log(`[embedded-assets] Successfully bundled ${Object.keys(assets).length} static assets into ${outputPath}`);
}

// Run directly if invoked from CLI
if (import.meta.main || process.argv[1] === new URL(import.meta.url).pathname) {
  generateEmbeddedAssets();
}
